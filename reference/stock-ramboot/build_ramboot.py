"""Reproducible fixed-ABI experimental loader build. Local compilation only."""
from pathlib import Path
import os,struct,subprocess
H=Path(__file__).resolve().parent
zig=H/'build-tools/ziglang/zig.exe'
env=dict(os.environ,ZIG_GLOBAL_CACHE_DIR=str(H/'zig-cache'))
def run(args):subprocess.run([str(zig),*args],env=env,check=True)
run(['cc','-target','aarch64-freestanding-none','-c',str(H/'ramboot_a64.S'),'-o',str(H/'ramboot_a64.o')])
b=(H/'ramboot_a64.o').read_bytes()
off=struct.unpack_from('<Q',b,40)[0];es,n,si=struct.unpack_from('<HHH',b,58)
sections=[struct.unpack_from('<IIQQQQIIQQ',b,off+i*es) for i in range(n)]
names=b[sections[si][4]:sections[si][4]+sections[si][5]]
named={names[s[0]:].split(b'\0')[0].decode():s for s in sections}
assert '.rela.text' not in named,named.keys()
s=named['.text'];payload=b[s[4]:s[4]+s[5]]
assert len(payload)==3584
(H/'ramboot_a64.bin').write_bytes(payload)
(H/'ramboot_a64_payload.h').write_text('/* Generated by build_ramboot.py. */\nstatic const unsigned char a64_payload[]={\n'+',\n'.join(','.join(f'0x{x:02x}' for x in payload[i:i+24]) for i in range(0,len(payload),24))+'\n};\n')
run(['cc','-target','aarch64-freestanding-none','-c',str(H/'ramfault.S'),'-o',str(H/'ramfault.o')])
f=(H/'ramfault.o').read_bytes();fo=struct.unpack_from('<Q',f,40)[0];fe,fn,fi=struct.unpack_from('<HHH',f,58)
fs=[struct.unpack_from('<IIQQQQIIQQ',f,fo+i*fe) for i in range(fn)]
strings=f[fs[fi][4]:fs[fi][4]+fs[fi][5]]
named_f={strings[s[0]:].split(b'\0')[0].decode():s for s in fs}
assert '.rela.text' not in named_f
sec=named_f['.text'];fault=f[sec[4]:sec[4]+sec[5]]
sym=named_f['.symtab'];st=fs[sym[6]];names_f=f[st[4]:st[4]+st[5]];literal=None
for at in range(sym[4],sym[4]+sym[5],sym[9]):
    no,info,other,si,value,size=struct.unpack_from('<IBBHQQ',f,at)
    if names_f[no:].split(b'\0')[0]==b'mf_fault_head_literal':literal=value
assert literal is not None and len(fault)<=0x180
(H/'ramfault.bin').write_bytes(fault)
(H/'ramfault_payload.h').write_text('/* Generated diagnostic fatal-path code. */\n#define RAMFAULT_HEAD_OFFSET '+str(literal)+'U\nstatic const unsigned char fault_payload[]={\n'+',\n'.join(','.join(f'0x{x:02x}' for x in fault[i:i+24]) for i in range(0,len(fault),24))+'\n};\n')
run(['cc','-target','aarch64-freestanding-none','-c',str(H/'mdio_probe.S'),'-o',str(H/'mdio_probe.o')])
mb=(H/'mdio_probe.o').read_bytes();mo=struct.unpack_from('<Q',mb,40)[0];me,mn,mi=struct.unpack_from('<HHH',mb,58)
ms=[struct.unpack_from('<IIQQQQIIQQ',mb,mo+i*me) for i in range(mn)]
mnames=mb[ms[mi][4]:ms[mi][4]+ms[mi][5]]
md={mnames[s[0]:].split(b'\0')[0].decode():s for s in ms}
assert '.rela.text' not in md
mt=md['.text'];mp=mb[mt[4]:mt[4]+mt[5]];assert len(fault)<=160 and len(mp)<=224
mss=md['.symtab'];mstr=ms[mss[6]];mst=mb[mstr[4]:mstr[4]+mstr[5]];constants={}
for at in range(mss[4],mss[4]+mss[5],mss[9]):
    no,info,other,si,value,size=struct.unpack_from('<IBBHQQ',mb,at)
    name=mst[no:].split(b'\0')[0].decode()
    if name in ['mdio_head_literal','mdio_force_literal','mdio_return_branch']:constants[name]=value
assert len(constants)==3
(H/'mdio_probe.bin').write_bytes(mp)
(H/'mdio_probe_payload.h').write_text('/* Generated MDIO board diagnostic. */\n'+
    ''.join('#define '+k.upper()+'_OFFSET '+str(v)+'U\n' for k,v in constants.items())+
    'static const unsigned char mdio_payload[]={\n'+',\n'.join(','.join(f'0x{x:02x}' for x in mp[i:i+24]) for i in range(0,len(mp),24))+'\n};\n')
for mode in ('prepare','execute'):
    run(['build-obj','-target','arm-freestanding-eabi','-mcpu','cortex_a7+soft_float',
        '-fno-PIC','-fno-PIE','-fno-unwind-tables','-O','ReleaseSmall',
        '-femit-bin='+str(H/f'mf297d_ramboot_{mode}.ko'),'-cflags',
        '-DRAMBOOT_EXECUTE_ENABLED='+str(int(mode=='execute')),
        '-marm','-mfloat-abi=soft','-fno-vectorize','-fno-slp-vectorize',
        '-ffreestanding','-fno-stack-protector','-fno-builtin','-fno-pic','-fno-pie',
        '-Wall','-Wextra','-Werror','--',str(H/'mf297d_ramboot.c')])
print('Built prepare/execute modules and relocation-free ARM64 diagnostic shim')
